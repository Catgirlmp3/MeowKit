#!/usr/bin/env bash

detect_resources() {
  begin_step 'Hardware and resource detection'
  [[ $(uname -m) == x86_64 ]] || fail 'This release currently supports x86_64 systems only.'
  TOTAL_THREADS=$(nproc 2>/dev/null || nproc --all)
  ((TOTAL_THREADS > 0)) || fail 'Could not detect available CPU threads.'
  TOTAL_RAM_MB=$(awk '/MemTotal:/ {print int($2/1024)}' /proc/meminfo)
  ((TOTAL_RAM_MB > 0)) || fail 'Could not detect physical RAM.'

  local guests=0
  if command -v qm >/dev/null 2>&1; then guests=$((guests + $(qm list 2>/dev/null | awk 'NR>1 && $3=="running" {n++} END{print n+0}'))); fi
  if command -v pct >/dev/null 2>&1; then guests=$((guests + $(pct list 2>/dev/null | awk 'NR>1 && $2=="running" {n++} END{print n+0}'))); fi

  CPU_PERCENT=${CPU_PERCENT:-75}
  RAM_PERCENT=${RAM_PERCENT:-75}
  [[ $CPU_PERCENT =~ ^[0-9]+$ ]] && ((CPU_PERCENT == 50 || CPU_PERCENT == 75)) || fail 'CPU allocation must be 50% or 75%. MeowKit never allocates below 50%.'
  [[ $RAM_PERCENT =~ ^[0-9]+$ ]] && ((RAM_PERCENT >= 10 && RAM_PERCENT <= 90)) || fail 'Huge-page RAM budget percentage must be between 10 and 90.'

  if [[ ${VM_MODE:-auto} == shared ]]; then CPU_PERCENT=50; fi
  if [[ ${VM_MODE:-auto} == auto ]] && ((guests > 0)) && ((CPU_PERCENT_EXPLICIT == 0)); then CPU_PERCENT=50; fi

  THREADS=$((TOTAL_THREADS * CPU_PERCENT / 100))
  ((THREADS >= (TOTAL_THREADS + 1) / 2)) || THREADS=$(((TOTAL_THREADS + 1) / 2))
  ((THREADS > 0)) || THREADS=1
  CPU_QUOTA=$((THREADS * 100))
  log "Available CPU threads: $TOTAL_THREADS; miner threads: $THREADS; CPU quota: ${CPU_QUOTA}%; RAM: ${TOTAL_RAM_MB} MiB; detected running Proxmox guests: $guests"
}

configure_hugepages() {
  begin_step 'Automatic huge-page sizing'
  install -d -m 755 "$MEOWKIT_DIR" /usr/local/sbin
  cat > "$MEOWKIT_DIR/hugepages.conf" <<EOF
RAM_PERCENT=$RAM_PERCENT
THREADS=$THREADS
EOF
  chmod 600 "$MEOWKIT_DIR/hugepages.conf"

  cat > /usr/local/sbin/meowkit-hugepages <<'EOFHP'
#!/usr/bin/env bash
set -u
CONFIG=/etc/meowkit/hugepages.conf
HP2=/sys/kernel/mm/hugepages/hugepages-2048kB/nr_hugepages
HP1=/sys/kernel/mm/hugepages/hugepages-1048576kB/nr_hugepages
RAM_PERCENT=75
THREADS=1
if [[ -r $CONFIG ]]; then
  # This file is generated by MeowKit and contains numeric assignments only.
  source "$CONFIG"
fi
[[ $RAM_PERCENT =~ ^[0-9]+$ ]] || RAM_PERCENT=75
[[ $THREADS =~ ^[0-9]+$ ]] || THREADS=1
MEM_TOTAL_MB=$(awk '/MemTotal:/ {print int($2/1024)}' /proc/meminfo)
MEM_AVAIL_MB=$(awk '/MemAvailable:/ {print int($2/1024)}' /proc/meminfo)
# Keep at least 1 GiB for the guest OS, plus 20% of RAM where possible.
RESERVE_MB=$((MEM_TOTAL_MB / 5))
(( RESERVE_MB < 1024 )) && RESERVE_MB=1024
AVAILABLE_BUDGET=$((MEM_AVAIL_MB - RESERVE_MB))
(( AVAILABLE_BUDGET > 0 )) || AVAILABLE_BUDGET=0
# RandomX uses one shared dataset (~2.5 GiB); add per-thread scratch space and headroom.
RANDOMX_MB=$((2800 + THREADS * 4))
TARGET_MB=$RANDOMX_MB
(( TARGET_MB > AVAILABLE_BUDGET )) && TARGET_MB=$AVAILABLE_BUDGET
TARGET_MB=$((TARGET_MB * RAM_PERCENT / 100))
TARGET_PAGES=$((TARGET_MB / 2))
if [[ -w $HP2 ]]; then
  CURRENT=$(cat "$HP2" 2>/dev/null || echo 0)
  if (( TARGET_PAGES > CURRENT )); then
    printf '%s\n' "$TARGET_PAGES" > "$HP2" 2>/dev/null || true
  fi
  echo "MeowKit: 2 MiB huge pages $(cat "$HP2" 2>/dev/null || echo "$CURRENT") (target $TARGET_PAGES; budget ${TARGET_MB} MiB; ${THREADS} threads)."
else
  echo 'MeowKit: 2 MiB huge pages unavailable; continuing without reservation.' >&2
fi

# 1 GiB pages are optional. Try a runtime reservation only when the kernel exposes it;
# failure is non-fatal because many VM kernels cannot allocate these pages after boot.
if [[ -w $HP1 ]]; then
  CURRENT1=$(cat "$HP1" 2>/dev/null || echo 0)
  if (( CURRENT1 == 0 && TARGET_MB >= 3072 )); then
    printf '1\n' > "$HP1" 2>/dev/null || true
  fi
  echo "MeowKit: 1 GiB huge pages $(cat "$HP1" 2>/dev/null || echo "$CURRENT1") reserved (optional)."
else
  echo 'MeowKit: 1 GiB huge pages not exposed by this kernel; skipped.' >&2
fi
EOFHP
  chmod 755 /usr/local/sbin/meowkit-hugepages
  /usr/local/sbin/meowkit-hugepages || info 'Huge-page helper reported an issue; continuing without the optimisation.'
}

configure_msr() {
  begin_step 'MSR support (automatic, non-fatal)'
  install -d -m 755 /etc/modules-load.d /etc/modprobe.d
  printf 'msr\n' > /etc/modules-load.d/meowkit-msr.conf
  printf 'options msr allow_writes=on\n' > /etc/modprobe.d/meowkit-msr.conf
  if modprobe msr 2>/dev/null; then
    if [[ -w /sys/module/msr/parameters/allow_writes ]]; then
      printf '1\n' > /sys/module/msr/parameters/allow_writes 2>/dev/null || true
    fi
    info 'MSR module loaded; write access enabled where supported.'
  else
    info 'MSR unavailable or blocked by the hypervisor/kernel; continuing without MSR tuning.'
  fi
}
