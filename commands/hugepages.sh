#!/usr/bin/env bash
set -u

D=${MEOWKIT_DIR:-/etc/meowkit}
CFG=$D/config.json
STATE=$D/hugepages-state
CONFIG=$D/hugepages.conf
HP2=/sys/kernel/mm/hugepages/hugepages-2048kB/nr_hugepages
HP1=/sys/kernel/mm/hugepages/hugepages-1048576kB/nr_hugepages
log(){ printf '[MeowKit hugepages] %s\n' "$*"; }

ACTION=${1:---apply}
case "$ACTION" in
  --apply) ;;
  --restore)
    if [[ -r $STATE ]]; then
      source "$STATE"
      for spec in "$HP1:BASELINE_ONE_GB_PAGES" "$HP2:BASELINE_TWO_MB_PAGES"; do
        path=${spec%%:*}; key=${spec#*:}; value=${!key:-}
        [[ $value =~ ^[0-9]+$ && -w $path ]] || continue
        printf '%s\n' "$value" > "$path" 2>/dev/null || log "Could not restore $path to its pre-MeowKit value."
      done
      log 'Attempted to restore pre-MeowKit huge-page reservations.'
    fi
    exit 0
    ;;
  *) log "Unknown option: $ACTION"; exit 2 ;;
esac

RAM_PERCENT=75
THREADS=1
HOST_RESERVE_MB=2048
if [[ -r $CONFIG ]]; then
  # Generated by MeowKit; contains numeric assignments only.
  source "$CONFIG"
fi
[[ $RAM_PERCENT =~ ^[0-9]+$ ]] && (( RAM_PERCENT >= 1 && RAM_PERCENT <= 100 )) || RAM_PERCENT=75
[[ $THREADS =~ ^[1-9][0-9]*$ ]] || THREADS=1
[[ $HOST_RESERVE_MB =~ ^[0-9]+$ ]] || HOST_RESERVE_MB=2048

TOTAL_MB=$(awk '/MemTotal:/ {print int($2/1024)}' /proc/meminfo)
[[ $TOTAL_MB =~ ^[1-9][0-9]*$ ]] || { log 'Cannot read physical RAM; leaving page reservations unchanged.'; exit 0; }

GUEST_MB=0
if command -v qm >/dev/null 2>&1; then
  while read -r id; do
    [[ $id =~ ^[0-9]+$ ]] || continue
    memory=$(qm config "$id" 2>/dev/null | awk -F: '$1=="memory"{gsub(/[[:space:]]/,"",$2);print $2;exit}')
    [[ $memory =~ ^[0-9]+$ ]] && GUEST_MB=$((GUEST_MB + memory))
  done < <(qm list 2>/dev/null | awk 'NR>1 && $3=="running"{print $1}')
fi
if command -v pct >/dev/null 2>&1; then
  while read -r id; do
    [[ $id =~ ^[0-9]+$ ]] || continue
    memory=$(pct config "$id" 2>/dev/null | awk -F: '$1=="memory"{gsub(/[[:space:]]/,"",$2);print $2;exit}')
    [[ $memory =~ ^[0-9]+$ ]] && GUEST_MB=$((GUEST_MB + memory))
  done < <(pct list 2>/dev/null | awk 'NR>1 && $2=="running"{print $1}')
fi

RESERVE_MB=$((TOTAL_MB / 5))
(( RESERVE_MB < HOST_RESERVE_MB )) && RESERVE_MB=$HOST_RESERVE_MB
SAFE_MB=$((TOTAL_MB - RESERVE_MB - GUEST_MB))
(( SAFE_MB > 0 )) || SAFE_MB=0
BUDGET_MB=$((SAFE_MB * RAM_PERCENT / 100))
# RandomX needs roughly 2.6 GiB plus a small per-thread scratch allowance.
REQUIRED_MB=$((2600 + THREADS * 4))
TARGET_MB=$REQUIRED_MB
(( TARGET_MB > BUDGET_MB )) && TARGET_MB=$BUDGET_MB

ACTUAL1=0; ACTUAL2=0
[[ -r $HP1 ]] && ACTUAL1=$(cat "$HP1" 2>/dev/null || echo 0)
[[ -r $HP2 ]] && ACTUAL2=$(cat "$HP2" 2>/dev/null || echo 0)
[[ $ACTUAL1 =~ ^[0-9]+$ ]] || ACTUAL1=0
[[ $ACTUAL2 =~ ^[0-9]+$ ]] || ACTUAL2=0
BASELINE1=$ACTUAL1; BASELINE2=$ACTUAL2
if [[ -r $STATE ]]; then
  old1=$(sed -n 's/^BASELINE_ONE_GB_PAGES=//p' "$STATE" | head -n1)
  old2=$(sed -n 's/^BASELINE_TWO_MB_PAGES=//p' "$STATE" | head -n1)
  [[ $old1 =~ ^[0-9]+$ ]] && BASELINE1=$old1
  [[ $old2 =~ ^[0-9]+$ ]] && BASELINE2=$old2
fi

# Preserve page reservations that pre-date MeowKit. Resize only the managed
# allocation, and do it while XMRig is stopped by the resource controller.
TARGET1=0
if (( TARGET_MB >= 2600 )) && [[ -w $HP1 ]]; then TARGET1=1; fi
DESIRED1=$BASELINE1
(( TARGET1 > DESIRED1 )) && DESIRED1=$TARGET1
if [[ -w $HP1 ]] && (( ACTUAL1 != DESIRED1 )); then
  printf '%s\n' "$DESIRED1" > "$HP1" 2>/dev/null || log "Could not resize 1 GiB pool to $DESIRED1; pages may still be in use."
  ACTUAL1=$(cat "$HP1" 2>/dev/null || echo "$ACTUAL1")
  [[ $ACTUAL1 =~ ^[0-9]+$ ]] || ACTUAL1=0
fi

ONE_GB=0
if (( TARGET_MB >= 2600 && ACTUAL1 >= 1 )); then ONE_GB=1; fi
REMAIN_MB=$((TARGET_MB - ACTUAL1 * 1024))
(( REMAIN_MB > 0 )) || REMAIN_MB=0
TARGET2=$(((REMAIN_MB + 1) / 2))
DESIRED2=$BASELINE2
(( TARGET2 > DESIRED2 )) && DESIRED2=$TARGET2
if [[ -w $HP2 ]] && (( ACTUAL2 != DESIRED2 )); then
  printf '%s\n' "$DESIRED2" > "$HP2" 2>/dev/null || log "Could not resize 2 MiB pool to $DESIRED2; pages may still be in use."
  ACTUAL2=$(cat "$HP2" 2>/dev/null || echo "$ACTUAL2")
  [[ $ACTUAL2 =~ ^[0-9]+$ ]] || ACTUAL2=0
fi

mkdir -p "$D"
tmp=$(mktemp "$D/.hugepages-state.XXXXXX") || exit 0
{
  printf 'BASELINE_ONE_GB_PAGES=%s\n' "$BASELINE1"
  printf 'BASELINE_TWO_MB_PAGES=%s\n' "$BASELINE2"
  printf 'ONE_GB_PAGES=%s\n' "$ONE_GB"
  printf 'GUEST_RESERVE_MB=%s\n' "$GUEST_MB"
  printf 'ONE_GB_ACTUAL_PAGES=%s\n' "$ACTUAL1"
  printf 'TWO_MB_ACTUAL_PAGES=%s\n' "$ACTUAL2"
} > "$tmp"
chmod 600 "$tmp"; mv -f "$tmp" "$STATE"

# Keep XMRig's 1 GiB setting in sync with what the kernel actually reserved.
if [[ -r $CFG ]] && command -v flock >/dev/null 2>&1; then
  exec 8>"$D/.config.lock"; flock -x 8
  python3 - "$CFG" "$ONE_GB" <<'PY'
import json, os, sys, tempfile
path, enabled = sys.argv[1], sys.argv[2] == "1"
try:
    with open(path, encoding="utf-8") as f: data=json.load(f)
    data.setdefault("randomx", {})["1gb-pages"] = enabled
    fd, tmp = tempfile.mkstemp(prefix=".config-hp.", dir=os.path.dirname(path))
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2); f.write("\n")
    os.chmod(tmp, 0o640); os.replace(tmp, path)
except Exception as exc:
    print(f"MeowKit hugepages: could not update XMRig config: {exc}", file=sys.stderr)
PY
  flock -u 8
fi

log "Guests reserve ${GUEST_MB} MiB; host reserve ${RESERVE_MB} MiB; safe RAM ${SAFE_MB} MiB; huge-page budget ${BUDGET_MB} MiB."
log "Managed target ${TARGET_MB} MiB; 1 GiB pages ${ACTUAL1}; 2 MiB pages ${ACTUAL2}; 1 GiB mode ${ONE_GB}."
